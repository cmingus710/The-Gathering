#!/usr/bin/env node
/**
 * Builds the web copies of the supplied section-header backgrounds.
 *
 *   npm run section:backgrounds            generate what is missing or stale
 *   npm run section:backgrounds -- --check list missing artwork and exit 1 if any
 *
 * Source: one charcoal/gold (dark) and one ivory/gold (light) banner per
 * section, listed in assets/section-headers/background-manifest.json and kept
 * in assets/brand/source/ (outside public/, so the multi-megabyte PNGs are
 * never served). They are never modified: each copy is a straight
 * proportional resize (no crop, no stretch, no recolour) to WebP at two
 * widths, so a phone never downloads a 2172 px PNG.
 *
 * Each run also samples the colour along the artwork's quiet left edge. The
 * header paints that colour behind and beside the artwork, so the banner can
 * be any width without stretching the image or showing a seam.
 *
 * Output: public/images/section-headers/<name>-<theme>-<width>.webp and
 * src/lib/section-headers/backgrounds.generated.ts. Runs before every build.
 */
import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST = path.join(root, "assets/section-headers/background-manifest.json");
const OUT_DIR = path.join(root, "public/images/section-headers");
const OUT_TS = path.join(root, "src/lib/section-headers/backgrounds.generated.ts");
/** The artwork shows at most ~640 CSS px wide in a header; 1280 covers 2× screens. */
const WIDTHS = [640, 1280];
const THEMES = ["dark", "light"];

const check = process.argv.includes("--check");
const manifest = JSON.parse(await readFile(MANIFEST, "utf8"));

const missing = [];
for (const entry of manifest) for (const theme of THEMES) if (!existsSync(path.join(root, entry[theme]))) missing.push(`${entry.name} (${theme}): ${entry[theme]}`);

if (check) {
  console.log(`Section backgrounds: ${manifest.length * 2 - missing.length} of ${manifest.length * 2} supplied.`);
  for (const m of missing) console.log(`  missing  ${m}`);
  process.exit(missing.length ? 1 : 0);
}

const previous = existsSync(OUT_TS) ? await readFile(OUT_TS, "utf8") : "";
const recorded = new Map(
  [...previous.matchAll(/"([\w-]+:(?:dark|light))": \{ version: "(\w+)", edge: "(#[0-9a-f]{6})" \}/g)].map((m) => [m[1], { version: m[2], edge: m[3] }]),
);

let sharp = null;
async function loadSharp() {
  sharp ??= (await import("sharp")).default;
  return sharp;
}

const hex = (n) => Math.round(n).toString(16).padStart(2, "0");
const available = {};
for (const entry of manifest) {
  for (const theme of THEMES) {
    const source = path.join(root, entry[theme]);
    if (!existsSync(source)) continue;
    const key = `${entry.name}:${theme}`;
    const bytes = await readFile(source);
    const version = createHash("sha256").update(bytes).digest("hex").slice(0, 10);
    const file = (w) => path.join(OUT_DIR, `${entry.name}-${theme}-${w}.webp`);
    const prior = recorded.get(key);
    if (prior?.version === version && WIDTHS.every((w) => existsSync(file(w)))) {
      available[key] = prior;
      continue;
    }
    let image;
    try {
      image = await loadSharp();
    } catch {
      console.warn(`sharp is not installed; ${entry[theme]} was not resized.`);
      continue;
    }
    const meta = await image(bytes).metadata();
    // Average colour of the leftmost 2% (the quiet side behind the title).
    const strip = Math.max(4, Math.round((meta.width ?? 0) * 0.02));
    const { channels } = await image(bytes).extract({ left: 0, top: 0, width: strip, height: meta.height }).removeAlpha().stats();
    const edge = `#${channels.slice(0, 3).map((c) => hex(c.mean)).join("")}`;
    await mkdir(OUT_DIR, { recursive: true });
    for (const width of WIDTHS) {
      await image(bytes)
        .resize({ width, withoutEnlargement: true, kernel: "lanczos3" })
        .webp({ quality: 78, effort: 5, smartSubsample: true })
        .toFile(file(width));
    }
    available[key] = { version, edge };
  }
}

const names = manifest.map((m) => m.name);
const body = `// Generated by scripts/generate-section-headers.mjs. Do not edit by hand.
// The supplied section-header backgrounds that exist, with the colour of each artwork's left edge.

export const SECTION_BACKGROUND_NAMES = ${JSON.stringify(names)} as const;
export type SectionBackgroundName = (typeof SECTION_BACKGROUND_NAMES)[number];

export const SECTION_BACKGROUND_WIDTHS = ${JSON.stringify(WIDTHS)} as const;

export const SECTION_BACKGROUNDS: Partial<Record<\`\${SectionBackgroundName}:\${"dark" | "light"}\`, { version: string; edge: string }>> = {${Object.entries(available)
  .map(([k, v]) => `\n  ${JSON.stringify(k)}: { version: ${JSON.stringify(v.version)}, edge: ${JSON.stringify(v.edge)} },`)
  .join("")}${Object.keys(available).length ? "\n" : ""}};
`;
await mkdir(path.dirname(OUT_TS), { recursive: true });
if (previous !== body) await writeFile(OUT_TS, body);
console.log(`Section backgrounds: ${Object.keys(available).length} of ${manifest.length * 2} available${missing.length ? ` (missing: ${missing.join("; ")})` : ""}.`);
