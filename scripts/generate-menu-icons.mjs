#!/usr/bin/env node
/**
 * Builds the responsive copies of the supplied home-menu artwork.
 *
 *   npm run menu:icons            generate what is missing or stale
 *   npm run menu:icons -- --check list missing artwork and exit 1 if any
 *
 * Source: the dimensional icons listed in assets/menu/icon-manifest.json,
 * supplied as 1254×1254 PNGs in assets/brand/source/<name>.png (outside
 * public/, so the multi-megabyte originals are never served). They are never
 * modified: each copy is a straight resize (fit "contain", no crop, no
 * recolour, no added label) to WebP at a few widths, so a 100 px tile never
 * downloads a 1254 px PNG.
 *
 * Output: public/images/menu/optimized/<name>-<width>.webp and
 * src/lib/home/menu-art.generated.ts, which lists the artwork that exists so
 * the launcher only references files that are really there (anything missing
 * falls back to the repository's original tile glyph). Runs before every
 * build, so artwork added straight to GitHub is picked up by the next deploy.
 */
import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST = path.join(root, "assets/menu/icon-manifest.json");
const OUT_DIR = path.join(root, "public/images/menu/optimized");
const OUT_TS = path.join(root, "src/lib/home/menu-art.generated.ts");
/** Tiles render at up to 7rem (112 CSS px); 336 covers 3× screens. */
const WIDTHS = [96, 160, 240, 336];

const check = process.argv.includes("--check");
const manifest = JSON.parse(await readFile(MANIFEST, "utf8"));

const present = [];
const missing = [];
for (const entry of manifest) {
  const source = path.join(root, entry.asset);
  if (existsSync(source)) present.push({ ...entry, source });
  else missing.push(entry);
}

if (check) {
  console.log(`Menu artwork: ${present.length} of ${manifest.length} supplied.`);
  for (const m of missing) console.log(`  missing  ${m.asset}  (${m.name})`);
  process.exit(missing.length ? 1 : 0);
}

// Content hashes recorded by the previous run: an unchanged source whose
// copies all exist is skipped, so a build from a fresh checkout is instant.
const previous = existsSync(OUT_TS) ? await readFile(OUT_TS, "utf8") : "";
const recorded = new Map([...previous.matchAll(/"([\w-]+)": \{ widths: (\[[\d,]*\]), version: "(\w+)" \}/g)].map((m) => [m[1], { widths: JSON.parse(m[2]), version: m[3] }]));

let sharp = null;
async function loadSharp() {
  sharp ??= (await import("sharp")).default;
  return sharp;
}

const available = [];
for (const entry of present) {
  const bytes = await readFile(entry.source);
  const version = createHash("sha256").update(bytes).digest("hex").slice(0, 10);
  const prior = recorded.get(entry.name);
  if (prior?.version === version && prior.widths.length && prior.widths.every((w) => existsSync(path.join(OUT_DIR, `${entry.name}-${w}.webp`)))) {
    available.push({ name: entry.name, widths: prior.widths, version });
    continue;
  }
  let image;
  try {
    image = await loadSharp();
  } catch {
    console.warn(`sharp is not installed; ${entry.asset} was not resized.`);
    continue;
  }
  const meta = await image(bytes).metadata();
  if (meta.format !== "png") throw new Error(`${entry.asset} is not a PNG.`);
  if (meta.width !== meta.height) console.warn(`${entry.asset} is ${meta.width}×${meta.height}; it will be letterboxed, never stretched.`);
  await mkdir(OUT_DIR, { recursive: true });
  const widths = WIDTHS.filter((w) => w <= (meta.width ?? 0));
  for (const width of widths) {
    await image(bytes)
      .resize(width, width, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 }, kernel: "lanczos3" })
      .webp({ quality: 86, alphaQuality: 100, effort: 4, smartSubsample: true })
      .toFile(path.join(OUT_DIR, `${entry.name}-${width}.webp`));
  }
  available.push({ name: entry.name, widths, version });
}

const body = `// Generated by scripts/generate-menu-icons.mjs. Do not edit by hand.
// Lists the supplied home-menu artwork that exists, with its responsive widths.

export const MENU_ART_NAMES = ${JSON.stringify(manifest.map((m) => m.name))} as const;
export type MenuArtName = (typeof MENU_ART_NAMES)[number];

export const MENU_ART: Partial<Record<MenuArtName, { widths: readonly number[]; version: string }>> = {${available
  .map((a) => `\n  ${JSON.stringify(a.name)}: { widths: ${JSON.stringify(a.widths)}, version: ${JSON.stringify(a.version)} },`)
  .join("")}${available.length ? "\n" : ""}};
`;
if (previous !== body) await writeFile(OUT_TS, body);
console.log(`Menu artwork: ${available.length} of ${manifest.length} available${missing.length ? ` (missing: ${missing.map((m) => m.name).join(", ")})` : ""}.`);
